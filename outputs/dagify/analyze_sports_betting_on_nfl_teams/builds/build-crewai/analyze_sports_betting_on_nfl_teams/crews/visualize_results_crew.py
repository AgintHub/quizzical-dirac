from typing import Dict, Any, List, Optional
from crewai import Agent, Task, Crew
from crewai.project import CrewBase, agent, crew, task
from .models import visualize_results_output

@CrewBase
class visualize_results_crew:
    """Crew for visualize_results operations."""


    @agent
    def visualize_results_agent(self):
        return Agent(
            role="Visualize Results Specialist",
            goal="""Execute visualize_results task accurately.
PRD Requirements:
- Use a combination of matplotlib and seaborn libraries to create visualizations
- Create a line chart to display team performance metrics over time
- Create a bar chart to display betting odds trends
- Create a scatter plot to display the relationship between team performance metrics and betting odds
- Use a summary statistics table to display insights generated by the analysis""",
            backstory="You are a specialized worker focused on Visualize the results of the analysis, including charts and graphs.",
            verbose=True
        )



    @task
    def visualize_results_task(self):
        """Task for visualize_results."""
        agent = self.visualize_results_agent()
        return Task(
            description="""Using {generate_insights_output}, Visualize the results of the analysis, including charts and graphs.""",
            agent=agent,
            expected_output="""{
    visualization_type: str  # Type of visualization (e.g., chart, graph, table)
    team_performance_metrics: list of floats  # List of team performance metrics (e.g., win rates, points scored)
    betting_odds_trends: list of strs  # List of trends and patterns in betting odds
    insights_summary: str  # Summary of the insights generated by the analysis
    recommendations: list of strs  # List of recommendations on which teams to bet on and which to avoid
}""",
            output_pydantic=visualize_results_output
        )


    @crew
    # @traceable
    def crew(self):
        """Create the crew instance."""
        return Crew(
            agents=[self.visualize_results_agent()],
            tasks=[self.visualize_results_task()],
            verbose=True
        )
